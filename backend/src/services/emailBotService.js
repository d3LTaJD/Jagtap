/**
 * Handles the creation of Customer, Enquiry, Task and Notification from a single email.
 */
async function processEmailMessage(parsed) {
  const fromText = parsed.from?.text || '';
  const senderEmail = (parsed.from?.value?.[0]?.address || extractEmail(fromText)).toLowerCase();
  const senderName = parsed.from?.value?.[0]?.name || fromText.split('<')[0].replace(/"/g, '').trim() || 'Email Sender';
  const subject = parsed.subject || 'No Subject';
  const bodyText = parsed.text || parsed.html?.replace(/<[^>]+>/g, '') || '';

  // 1. Try to match an existing enquiry by Reference ID in subject
  let enquiry = null;
  const refMatch = subject.match(/(ENQ-\d{4}-\d{2}-\d{4})/i);
  if (refMatch) {
    const matchedId = refMatch[1].toUpperCase();
    console.log(`[Email Bot] Found reference ID ${matchedId} in subject. Searching for Enquiry...`);
    enquiry = await Enquiry.findOne({ enquiryId: matchedId }).populate('customer');
  }

  // 2. Fallback: match by customer email if they have exactly one active enquiry and subject indicates a reply thread
  if (!enquiry) {
    const isReplySubject = /^(re|fwd|fw)\s*:/i.test(subject.trim());
    if (isReplySubject) {
      const customer = await Customer.findOne({
        $or: [
          { emailAddress: senderEmail },
          { alternateEmail: senderEmail }
        ]
      });
      if (customer) {
        const activeEnquiries = await Enquiry.find({
          customer: customer._id,
          status: { $in: ['New', 'Contacted', 'Technical Review'] }
        }).populate('customer');
        
        if (activeEnquiries.length === 1) {
          enquiry = activeEnquiries[0];
          console.log(`[Email Bot] Fallback match: Customer has exactly one active Enquiry (${enquiry.enquiryId}) and subject indicates a thread. Treating email as reply.`);
        }
      }
    }
  }

  // 3. If an existing enquiry is matched, update its dynamic specs and metadata
  if (enquiry) {
    console.log(`[Email Bot] Processing consequent email for existing Enquiry ${enquiry.enquiryId}`);
    
    // Fetch active FieldDefinitions for this category
    const FieldDefinition = require('../models/FieldDefinition');
    const fields = await FieldDefinition.find({
      formContext: 'Enquiry',
      isDeleted: false,
      isActive: true,
      $or: [
        { productCategory: enquiry.productCategory },
        { productCategory: null },
        { productCategory: '' }
      ]
    });

    // Extract dynamic fields from email body via AI
    const extractedFields = await aiService.extractDynamicFields(bodyText, fields);
    console.log(`[Email Bot] Extracted dynamic fields from reply:`, JSON.stringify(extractedFields, null, 2));

    // Merge dynamic fields
    enquiry.dynamicFields = {
      ...(enquiry.dynamicFields || {}),
      ...extractedFields
    };

    // Extract other standard fields using AI (e.g. quantity, standardCode etc. if they were updated)
    const extractedMeta = await aiService.extractEnquiryDetails(bodyText, { from: fromText, subject });
    if (extractedMeta.isEnquiry !== false) {
      if (extractedMeta.quantity && extractedMeta.quantity > 1 && enquiry.quantity === 1) {
        enquiry.quantity = extractedMeta.quantity;
      }
      if (extractedMeta.standardCode && extractedMeta.standardCode !== 'Not specified' && enquiry.standardCode === 'Not specified') {
        enquiry.standardCode = extractedMeta.standardCode;
      }
      if (extractedMeta.specialRequirements && !enquiry.specialRequirements) {
        enquiry.specialRequirements = extractedMeta.specialRequirements;
      }
    }

    // Save and check completeness
    const { checkEnquiryCompletion } = require('../controllers/enquiryController');
    const completion = await checkEnquiryCompletion(enquiry);
    if (completion.isComplete && ['New', 'Contacted', 'Technical Review'].includes(enquiry.status)) {
      enquiry.status = 'Ready for Offer';
      if (enquiry.assignedTo) {
        await createNotification({
          user_id: enquiry.assignedTo,
          type: 'SYSTEM',
          title: '🎉 Enquiry Ready for Offer',
          message: `Enquiry ${enquiry.enquiryId} is now Ready for Offer! Required fields filled via email reply.`,
          related_id: enquiry._id
        });
      }
    }
    await enquiry.save();

    // Create a FollowUp record — strip quoted reply chains from the body
    const cleanBody = stripQuotedText(bodyText);
    const noteText = `📧 Reply received.\nSubject: ${subject}\n\n${cleanBody || '(No new content in reply)'}`.slice(0, 2000);
    const followUpAgent = enquiry.assignedTo || enquiry.createdBy;
    if (followUpAgent) {
      await FollowUp.create({
        enquiry: enquiry._id,
        type: 'EMAIL',
        notes: noteText,
        addedBy: followUpAgent,
        followUpDate: new Date()
      });
    }

    // Send updated reply with current missing/complete status
    try {
      await sendAutomatedReply(senderEmail, enquiry.contactPerson || 'Customer', enquiry.enquiryId, {
        productDescription: enquiry.productDescription,
        productCategory: enquiry.productCategory,
        quantity: enquiry.quantity,
        unit: enquiry.unit,
        priority: enquiry.priority
      }, completion.missingFields);
    } catch (smtpErr) {
      console.error(`[Email Bot] Failed to send thread reply:`, smtpErr.message);
    }

    return;
  }

  // 4. Otherwise, extract structured lead via AI for new enquiry
  const extracted = await aiService.extractEnquiryDetails(bodyText, { from: fromText, subject });

  // Check if AI classified it as an actual business enquiry
  if (extracted.isEnquiry === false) {
    console.log(`[Email Bot] Email from ${senderEmail} classified by AI as NOT a business enquiry. Skipping DB insertion.`);
    return;
  }

  // Find or create Customer
  let customer = await Customer.findOne({ 
    $or: [
      { emailAddress: senderEmail.toLowerCase() },
      { alternateEmail: senderEmail.toLowerCase() }
    ]
  });

  if (!customer) {
    console.log(`[Email Bot] Customer not found. Auto-creating customer for ${senderEmail}`);
    customer = await Customer.create({
      companyName: extracted.companyName || 'Individual Customer',
      primaryContactName: extracted.primaryContactName || senderName,
      mobileNumber: extracted.mobileNumber || '0000000000',
      emailAddress: senderEmail.toLowerCase(),
      customerId: `CUS-${Date.now().toString().slice(-6)}`,
      sourceChannel: 'Email'
    });
  }

  // Find a default user to assign (Super Admin / Director / Sales)
  const defaultAgent = await User.findOne({ is_active: true, role: { $in: ['SUPER_ADMIN', 'DIRECTOR', 'SA', 'DIR'] } }) || await User.findOne({ is_active: true });
  const agentId = defaultAgent ? defaultAgent._id : null;

  // Generate sequential Enquiry ID
  const year = new Date().getFullYear();
  const month = String(new Date().getMonth() + 1).padStart(2, '0');
  const prefix = `ENQ-${year}-${month}-`;
  const seq = await getNextSequenceValue(prefix);
  const enquiryId = `${prefix}${String(seq).padStart(4, '0')}`;

  // Fetch active FieldDefinitions for this category to extract dynamic fields on creation
  const FieldDefinition = require('../models/FieldDefinition');
  const fields = await FieldDefinition.find({
    formContext: 'Enquiry',
    isDeleted: false,
    isActive: true,
    $or: [
      { productCategory: extracted.productCategory },
      { productCategory: null },
      { productCategory: '' }
    ]
  });

  // Extract dynamic fields from email body via AI/heuristics
  const extractedFields = await aiService.extractDynamicFields(bodyText, fields);
  console.log(`[Email Bot] Extracted dynamic fields on creation:`, JSON.stringify(extractedFields, null, 2));

  // Create Enquiry
  enquiry = await Enquiry.create({
    enquiryId,
    customer: customer._id,
    sourceChannel: 'Email',
    emailAccount: 'info@', // Default account designation
    contactPerson: extracted.primaryContactName || customer.primaryContactName,
    contactMobile: extracted.mobileNumber || customer.mobileNumber,
    contactEmail: senderEmail.toLowerCase(),
    productCategory: extracted.productCategory,
    productDescription: extracted.productDescription,
    quantity: extracted.quantity,
    unit: extracted.unit,
    standardCode: extracted.standardCode,
    specialRequirements: extracted.specialRequirements,
    priority: extracted.priority,
    assignedTo: agentId,
    createdBy: agentId,
    status: 'New',
    dynamicFields: extractedFields
  });

  console.log(`[Email Bot] Auto-created Enquiry ${enquiryId} for Customer ${customer.companyName}`);

  // Create System Follow-up Task and Notification
  if (agentId) {
    const due = new Date();
    due.setDate(due.getDate() + 1); // Due tomorrow
    
    await Task.create({
      title: `Review Email Enquiry ${enquiryId}`,
      description: `System generated task to review and follow up with the customer regarding: ${extracted.productDescription}.`,
      dueDate: due,
      priority: extracted.priority === 'Urgent' ? 'High' : 'Medium',
      status: 'To Do',
      assignedTo: agentId,
      createdBy: agentId,
      linkedEnquiry: enquiry._id
    });

    await createNotification({
      user_id: agentId,
      type: 'ENQUIRY_ASSIGNED',
      title: '📩 New Lead from Email',
      message: `Enquiry ${enquiryId} auto-created for ${customer.companyName} (${extracted.productCategory}).`,
      related_id: enquiry._id
    });
  }

  // Check completeness and update status
  const { checkEnquiryCompletion } = require('../controllers/enquiryController');
  const completion = await checkEnquiryCompletion(enquiry);
  if (completion.isComplete) {
    enquiry.status = 'Ready for Offer';
    await enquiry.save();
  }

  // Send Automated SMTP Reply to Customer with missing fields if any
  try {
    await sendAutomatedReply(senderEmail, extracted.primaryContactName || senderName, enquiryId, extracted, completion.missingFields);
  } catch (smtpErr) {
    console.error(`[Email Bot] Failed to send SMTP reply to ${senderEmail}:`, smtpErr.message);
  }
}

/**
 * Checks the inbox for unseen emails, parses them, and runs extraction/replies.
 */
async function checkEmails() {
  if (isProcessing) {
    console.log('[Email Bot] Previous execution is still processing. Skipping...');
    return;
  }
  isProcessing = true;

  const imapHost = process.env.IMAP_HOST;
  const imapPort = parseInt(process.env.IMAP_PORT || 993, 10);
  const imapUser = process.env.IMAP_USER;
  const imapPass = process.env.IMAP_PASS;

  if (!imapHost || !imapUser || !imapPass) {
    console.warn('[Email Bot] IMAP credentials or host missing in environment variables. Email bot polling skipped.');
    isProcessing = false;
    return;
  }

  const client = new ImapFlow({
    host: imapHost,
    port: imapPort,
    secure: true,
    auth: {
      user: imapUser,
      pass: imapPass
    },
    logger: false,
    connectionTimeout: 10000,
    greetingTimeout: 10000
  });

  try {
    console.log(`[Email Bot] Connecting to IMAP mailbox: ${imapHost}:${imapPort} as ${imapUser}...`);
    await client.connect();
    
    // Lock INBOX folder to perform operations
    let lock = await client.getMailboxLock('INBOX');
    try {
      // Find UIDs of all unseen (unread) messages
      const uids = await client.search({ seen: false }, { uid: true });
      console.log(`[Email Bot] Found ${uids.length} unseen email(s) in INBOX.`);

      for (const uid of uids) {
        console.log(`[Email Bot] Fetching raw message source for UID ${uid}...`);
        try {
          const emailStream = await client.download(uid, null, { uid: true });
          const parsed = await simpleParser(emailStream.content);
          
          // Check if auto-generated, bounce, or spam/notification
          const spamCheck = isAutoGeneratedOrSpam(parsed);
          if (spamCheck.isSpam) {
            console.log(`[Email Bot] Skipping UID ${uid}: ${spamCheck.reason}`);
            // Mark the email as SEEN (read) so we don't process it again
            await client.messageFlagsAdd(uid, ['\\Seen'], { uid: true });
            continue;
          }
          
          // Process the parsed message
          await processEmailMessage(parsed);
          
          // Mark the email as SEEN (read)
          await client.messageFlagsAdd(uid, ['\\Seen'], { uid: true });
          console.log(`[Email Bot] Successfully processed and marked UID ${uid} as SEEN.`);
        } catch (msgErr) {
          console.error(`[Email Bot] Failed to process message UID ${uid}:`, msgErr);
        }
      }
    } finally {
      // Release lock on INBOX
      lock.release();
    }
    
    await client.logout();
    console.log('[Email Bot] Logged out from IMAP box successfully.');
  } catch (err) {
    console.error('[Email Bot] Connection/processing failed:', err.message);
  } finally {
    isProcessing = false;
  }
}

/**
 * Starts the background polling worker.
 * Checks the inbox immediately, then polls every 1 minute.
 */
exports.start = () => {
  if (intervalId) {
    console.log('[Email Bot] Worker already running.');
    return;
  }
  
  console.log('[Email Bot] Starting background AI email processing service (1-minute polling interval)...');
  
  // Initial run
  checkEmails();
  
  // Setup interval
  intervalId = setInterval(checkEmails, 60000);
};

/**
 * Stops the background worker.
 */
exports.stop = () => {
  if (intervalId) {
    clearInterval(intervalId);
    intervalId = null;
    console.log('[Email Bot] Background worker stopped.');
  }
};

